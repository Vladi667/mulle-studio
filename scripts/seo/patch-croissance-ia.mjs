/* ─────────────────────────────────────────────────────────────────
   patch-croissance-ia.mjs — say what people type, on the page that ranks
   ─────────────────────────────────────────────────────────────────
   /fr/systemes-croissance-ia is the only non-brand page in reach: position
   28 for its own coinage, and "stack de croissance ia" at 22.3 with 18
   impressions — a phrase the page does not even contain. Live Google CH
   (2026-09-05) for "automatisation ia pme suisse / genève" is held by solo
   operators and 2026-dated micro-sites, not authority: relevance decides.
   The page ranks #3 for "systèmes de croissance ia" and #1 for "growth ops
   pme", and is absent for everything people actually type.

   So: keep the brand phrase, add the typed vocabulary. Title and meta name
   "automatisation IA pour PME"; the lead names "stack de croissance IA";
   one H3 names the dashboard-and-reporting deliverable the CHF 390/month
   tier already describes in a list item nobody can search; one FAQ item
   answers "Qu'est-ce qu'un stack de croissance IA ?". Nothing invented:
   every sentence restates what the page already says.

   This band is generated by enhance-twins.mjs from w4-data.json, which
   still carries pre-cut prices, so the band is never rebuilt; this patches
   the rendered HTML, marker-delimited and idempotent. Run
   patch-twin-schema.mjs AFTER it so the FAQPage schema follows the page.

     node scripts/seo/patch-croissance-ia.mjs
   ───────────────────────────────────────────────────────────────── */
import { load } from 'cheerio';
import { readFileSync, writeFileSync } from 'node:fs';
import { PRICES, CHF } from './prices.mjs';

const ROOT = 'C:/Users/Admin/Desktop/mulle-studio';
const FILE = `${ROOT}/fr/systemes-croissance-ia.html`;
const MARK = 'data-croissance-patch';
const SIGNAL = CHF(PRICES.growthOps.signal);

const TITLE = `Automatisation IA pour PME à Genève : systèmes de croissance | Agence Fritz`;
const META = `Automatisation IA pour PME à Genève et en Suisse romande : tracking, CRM, relances, tableau de bord et reporting automatisés, réunis en un système de croissance. Dès ${SIGNAL}/mois, prix publiés.`;

const LEAD_ADD = ` On parle aussi d'automatisation IA pour PME, ou de stack de croissance IA : la pile d'outils et de flux qui exécute, relance et mesure sans intervention manuelle.`;

const H3_SECTION = `<h3 ${MARK}="h3">Tableau de bord PME et reporting automatisé</h3>
<p ${MARK}="p">Le premier livrable du forfait Signal (${SIGNAL} par mois) est un tableau de bord unifié : vos sources de données reliées entre elles, un suivi hebdomadaire qui se met à jour seul, et un résumé réellement lisible plutôt qu'un export brut. C'est le socle sur lequel les automatisations suivantes viennent se poser, et la raison pour laquelle le système se cumule au lieu de se remplacer.</p>`;

const FAQ_ITEM = `<div class="lp-faq-item" ${MARK}="faq"><h3>Qu'est-ce qu'un stack de croissance IA ?</h3><p>Un stack de croissance IA est l'ensemble des outils et des flux automatisés qui relient vos données, vos relances et votre reporting : une source unique de vérité, une qualification et des relances automatiques, un tableau de bord qui se met à jour seul. Chez Fritz, il se construit par étapes, du forfait Signal à ${SIGNAL} par mois aux opérations pilotées, et l'infrastructure reste la vôtre.</p></div>`;

let html = readFileSync(FILE, 'utf8');
const $ = load(html, { decodeEntities: false });

// strip previous run
$(`[${MARK}]`).remove();
$('.lp-seo-intro').each((_, el) => { $(el).html($(el).html().replace(LEAD_ADD, '')); });

// 1. title + meta
$('title').text(TITLE);
$('meta[name="description"]').attr('content', META);
$('meta[property="og:title"]').attr('content', TITLE);
$('meta[property="og:description"]').attr('content', META);

// 2. lead sentence
const intro = $('.lp-seo-intro').first();
if (!intro.length) throw new Error('no .lp-seo-intro on the page');
intro.html(intro.html().trimEnd() + LEAD_ADD);

// 3. H3 section, placed before the FAQ block (the FAQ items' shared parent).
//    No newline padding: the strip step removes the marked elements but not a
//    bare text node beside them, and a stray "\n" per run is exactly the kind of
//    drift that makes a second run differ from the first.
const firstFaq = $('.lp-faq-item').first();
if (!firstFaq.length) throw new Error('no .lp-faq-item on the page');
firstFaq.parent().before(H3_SECTION);

// 4. FAQ item appended after the last existing one
$('.lp-faq-item').last().after(FAQ_ITEM);

/* cheerio serialises boolean attributes as defer="" and leaves a blank line where
   a removed node stood. Neither changes the page, but both make the second run
   differ from the first, and "idempotent" has to mean byte-identical. */
const out = $.html()
  .replace(/ (defer|async|crossorigin|hidden|novalidate|data-1p-ignore)=""/g, ' $1')
  .replace(/\n{3,}/g, '\n\n');
if (out !== html) { writeFileSync(FILE, out); console.log('patched fr/systemes-croissance-ia.html'); }
else console.log('already current');

// verification
const s = readFileSync(FILE, 'utf8');
const checks = {
  'title carries the typed phrase': /<title>Automatisation IA pour PME à Genève/.test(s),
  'brand phrase kept in H2': /<h2 id="lp-seo-h2">Systèmes de croissance IA/.test(s),
  'lead names stack de croissance IA': s.includes('stack de croissance IA'),
  'one dashboard H3': (s.match(new RegExp(`${MARK}="h3"`, 'g')) || []).length === 1,
  'one new FAQ item': (s.match(new RegExp(`${MARK}="faq"`, 'g')) || []).length === 1,
  'six visible FAQ items': (s.match(/class="lp-faq-item"/g) || []).length === 6,
  'no em dash in inserted copy': !/[—–]/.test(H3_SECTION + FAQ_ITEM + LEAD_ADD + META),
  'price from prices.mjs': s.includes(SIGNAL),
};
let bad = 0;
for (const [k, v] of Object.entries(checks)) { console.log(`   ${v ? 'ok  ' : 'FAIL'} ${k}`); if (!v) bad++; }
if (bad) process.exitCode = 1;
